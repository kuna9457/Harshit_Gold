# Macro & FX proxies:
# - ^TNX: US 10-Year Treasury Yield (Real Yield proxy)
# - ^IRX: US 13-Week Treasury Bill (Fed Repo / Funds Rate proxy)
# - DX-Y.NYB: US Dollar Index (DXY)

# 1. Ingest Pure Macro Data Feeds
tickers = {
    'Gold': 'GC=F',       # Comex Gold Futures
    'DXY': 'DX-Y.NYB',    # US Dollar Index
    'US10Y': '^TNX',      # US 10-Year Treasury Yield
    'USDINR': 'USDINR=X'  # FX Multiplier
}

series_dict = {}
for name, ticker in tickers.items():
    data = yf.Ticker(ticker).history(period="5y", interval="1d")['Close']
    data.index = data.index.tz_localize(None) # Strip timezones for clean alignment
    series_dict[name] = data

# Merge and forward-fill weekend/macro reporting gaps
df = pd.DataFrame(series_dict).ffill().dropna()

# 2. Feature Engineering: Rolling Z-Scores (50-Day Regime Window)
dxy_mean = df['DXY'].rolling(50).mean()
dxy_std = df['DXY'].rolling(50).std()
df['Z_DXY'] = -1 * ((df['DXY'] - dxy_mean) / dxy_std)  # Inverted (Weak Dollar = Bullish Gold)

yield_mean = df['US10Y'].rolling(50).mean()
yield_std = df['US10Y'].rolling(50).std()
df['Z_Yield'] = -1 * ((df['US10Y'] - yield_mean) / yield_std)  # Inverted (Falling Yields = Bullish Gold)

# Composite Macro Regime Score
df['Composite_Macro'] = (0.5 * df['Z_DXY']) + (0.5 * df['Z_Yield'])

# 3. Pure Macro Strategy Execution Rules
# Long (+1) when Macro Score is positive, otherwise hold Cash (0)
df['Position'] = np.where(df['Composite_Macro'] > 0.0, 1, 0)

# 4. Rolling Correlation Metrics
df['DXY_Corr'] = df['Gold'].pct_change().rolling(60).corr(df['DXY'].pct_change())
df['Yield_Corr'] = df['Gold'].pct_change().rolling(60).corr(df['US10Y'].pct_change())

# 5. Backtest Engine (1-Day Execution Lag to prevent lookahead bias)
df['Gold_Return'] = np.log(df['Gold'] / df['Gold'].shift(1))
df['Strategy_Return'] = df['Position'].shift(1) * df['Gold_Return']

df.dropna(inplace=True)

# Cumulative Returns
df['Cum_Gold'] = np.exp(df['Gold_Return'].cumsum())
df['Cum_Strategy'] = np.exp(df['Strategy_Return'].cumsum())

# 6. Performance & Risk Metrics
total_gold_ret = (df['Cum_Gold'].iloc[-1] - 1) * 100
total_strat_ret = (df['Cum_Strategy'].iloc[-1] - 1) * 100

years = len(df) / 252
cagr_gold = ((df['Cum_Gold'].iloc[-1]) ** (1 / years) - 1) * 100
cagr_strat = ((df['Cum_Strategy'].iloc[-1]) ** (1 / years) - 1) * 100

# Max Drawdown Calculation
peak_gold = df['Cum_Gold'].cummax()
dd_gold = ((df['Cum_Gold'] - peak_gold) / peak_gold).min() * 100

peak_strat = df['Cum_Strategy'].cummax()
dd_strat = ((df['Cum_Strategy'] - peak_strat) / peak_strat).min() * 100


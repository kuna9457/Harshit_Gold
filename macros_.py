macro_tickers = {
    'Real_Yield': '^TNX',
    'Fed_Rate': '^IRX',
    'DXY': 'DX-Y.NYB',
    'USDINR': 'USDINR=X',
    'CPI_Proxy': 'TIP'
}

macro_series = {}
for name, sym in macro_tickers.items():
    s = yf.Ticker(sym).history(period="5y", interval="1d")['Close']
    if s.index.tz is not None:
        s.index = s.index.tz_localize(None)
    macro_series[name] = s

# Combine into master DataFrame
df = pd.DataFrame({
    'Open': gold_raw['Open'],
    'High': gold_raw['High'],
    'Low': gold_raw['Low'],
    'Close': gold_raw['Close'],
    'Volume': gold_raw['Volume'].replace(0, np.nan)
})

for name, s in macro_series.items():
    df[name] = s

df = df.ffill().dropna().copy()

# ---------------------------------------------------------
# 2. FEATURE ENGINEERING: MACRO & TECHNICAL MATRIX
# ---------------------------------------------------------
WINDOW = 60  # Regime lookback window

def calc_zscore(series, window):
    mean = series.rolling(window).mean()
    std = series.rolling(window).std()
    return (series - mean) / std

# A. Directional Macro Z-Scores
df['Z_RealYield'] = -1.0 * calc_zscore(df['Real_Yield'], WINDOW)
df['Z_FedRate']   = -1.0 * calc_zscore(df['Fed_Rate'], WINDOW)
df['Z_DXY']       = -1.0 * calc_zscore(df['DXY'], WINDOW)
df['Z_USDINR']    =  1.0 * calc_zscore(df['USDINR'], WINDOW)
df['Z_CPI']       =  1.0 * calc_zscore(df['CPI_Proxy'], WINDOW)

# Weighted Composite Macro Score (Scores: 8, 8, 8, 2, 8; Total = 34)
total_score = 8 + 8 + 8 + 2 + 8
df['Composite_Macro'] = (
    (8 / total_score * df['Z_RealYield']) +
    (8 / total_score * df['Z_FedRate']) +
    (8 / total_score * df['Z_DXY']) +
    (2 / total_score * df['Z_USDINR']) +
    (8 / total_score * df['Z_CPI'])
)

# B. Technical Parameters: ATR(14) Volatility Expansion
df['Prev_Close'] = df['Close'].shift(1)
df['TR'] = np.maximum(
    df['High'] - df['Low'],
    np.maximum(
        (df['High'] - df['Prev_Close']).abs(),
        (df['Low'] - df['Prev_Close']).abs()
    )
)
df['ATR_14'] = df['TR'].rolling(14).mean()
df['ATR_Baseline'] = df['ATR_14'].rolling(30).mean()

# C. Technical Parameters: Volume Expansion (Institutional Footprint)
df['Vol_Baseline'] = df['Volume'].rolling(20).mean()

# D. Gold Momentum Z-Score
df['Z_Gold_Mom'] = calc_zscore(df['Close'], WINDOW)

# ---------------------------------------------------------
# 3. CONFLUENCE SCORE & MULTI-GATE EXECUTION ENGINE
# ---------------------------------------------------------
# Confluence Gates:
gate_macro   = df['Composite_Macro'] > 0.0          # Macro tailwind
gate_volat   = df['ATR_14'] > df['ATR_Baseline']    # Volatility expanding
gate_volume  = df['Volume'] > (1.2 * df['Vol_Baseline']) # Volume confirmation
gate_mom     = df['Z_Gold_Mom'] > 0.0               # Positive momentum

# Normalized Confluence Score (0 to 100% agreement)
df['Confluence_Score'] = (
    (gate_macro.astype(int) * 0.40) +
    (gate_volat.astype(int) * 0.20) +
    (gate_volume.astype(int) * 0.20) +
    (gate_mom.astype(int) * 0.20)
) * 100

# Entry: Triggered when confluence hits >= 80% (Macro + Volatility + Volume + Mom align)
df['Entry_Signal'] = (df['Confluence_Score'] >= 80).astype(int)

# Swing State Machine: Enter on confluence, hold until momentum flips or macro severely deteriorates
position = 0
positions = []
entries = []
exits = []

for i in range(len(df)):
    entry_trigger = df['Entry_Signal'].iloc[i]
    z_mom = df['Z_Gold_Mom'].iloc[i]
    macro_score = df['Composite_Macro'].iloc[i]

    # Entry Trigger
    if position == 0 and entry_trigger == 1:
        position = 1
        entries.append(df['Close'].iloc[i])
        exits.append(np.nan)
    # Exit Trigger: Momentum breakdown or Macro regime turns sharply negative
    elif position == 1 and (z_mom < -0.5 or macro_score < -0.5):
        position = 0
        entries.append(np.nan)
        exits.append(df['Close'].iloc[i])
    else:
        entries.append(np.nan)
        exits.append(np.nan)

    positions.append(position)


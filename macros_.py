import yfinance as yf
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from google.colab import files

# ---------------------------------------------------------
# 1. DATA INGESTION (Fetch once to save API calls)
# ---------------------------------------------------------
print("Fetching market data...")
gold_ticker = yf.Ticker("GC=F")
gold_raw = gold_ticker.history(period="5y", interval="1d")
if gold_raw.index.tz is not None:
    gold_raw.index = gold_raw.index.tz_localize(None)

macro_tickers = {'Real_Yield': '^TNX', 'Fed_Rate': '^IRX', 'DXY': 'DX-Y.NYB', 'USDINR': 'USDINR=X', 'CPI_Proxy': 'TIP'}
macro_series = {}
for name, sym in macro_tickers.items():
    s = yf.Ticker(sym).history(period="5y", interval="1d")['Close']
    if s.index.tz is not None:
        s.index = s.index.tz_localize(None)
    macro_series[name] = s

df = pd.DataFrame({'High': gold_raw['High'], 'Low': gold_raw['Low'], 'Close': gold_raw['Close'], 'Volume': gold_raw['Volume'].replace(0, np.nan)})
for name, s in macro_series.items():
    df[name] = s

df = df.ffill().dropna().copy()

# ---------------------------------------------------------
# 2. STATIC FEATURE ENGINEERING (Calculated once)
# ---------------------------------------------------------
WINDOW = 60
def calc_zscore(series, window):
    return (series - series.rolling(window).mean()) / series.rolling(window).std()

df['Z_RealYield'] = -1.0 * calc_zscore(df['Real_Yield'], WINDOW)
df['Z_FedRate']   = -1.0 * calc_zscore(df['Fed_Rate'], WINDOW)
df['Z_DXY']       = -1.0 * calc_zscore(df['DXY'], WINDOW)
df['Z_USDINR']    =  1.0 * calc_zscore(df['USDINR'], WINDOW)
df['Z_CPI']       =  1.0 * calc_zscore(df['CPI_Proxy'], WINDOW)

df['Composite_Macro'] = ( (8/34 * df['Z_RealYield']) + (8/34 * df['Z_FedRate']) + (8/34 * df['Z_DXY']) + (2/34 * df['Z_USDINR']) + (8/34 * df['Z_CPI']) )
df['Vol_Baseline'] = df['Volume'].rolling(20).mean()
df['Z_Gold_Mom'] = calc_zscore(df['Close'], WINDOW)
df['Gold_Ret'] = np.log(df['Close'] / df['Close'].shift(1))

# True Range calculation
df['Prev_Close'] = df['Close'].shift(1)
df['TR'] = np.maximum(df['High'] - df['Low'], np.maximum((df['High'] - df['Prev_Close']).abs(), (df['Low'] - df['Prev_Close']).abs()))

# ---------------------------------------------------------
# 3. ATR PARAMETER SWEEP (14 to 50)
# ---------------------------------------------------------
print("Running parameter optimization from ATR 14 to 50...")
optimization_results = []

# Loop through every ATR value
for atr_period in range(14, 51):
    df_sim = df.copy()

    # Calculate dynamic ATR based on current loop parameter
    df_sim['ATR_Dynamic'] = df_sim['TR'].rolling(atr_period).mean()
    # Baseline is kept as a 30-day average of the current ATR
    df_sim['ATR_Baseline'] = df_sim['ATR_Dynamic'].rolling(30).mean()

    # Confluence Gates
    gate_macro   = df_sim['Composite_Macro'] > 0.0
    gate_volat   = df_sim['ATR_Dynamic'] > df_sim['ATR_Baseline']
    gate_volume  = df_sim['Volume'] > (1.2 * df_sim['Vol_Baseline'])
    gate_mom     = df_sim['Z_Gold_Mom'] > 0.0

    df_sim['Confluence_Score'] = ((gate_macro.astype(int) * 0.40) + (gate_volat.astype(int) * 0.20) + (gate_volume.astype(int) * 0.20) + (gate_mom.astype(int) * 0.20)) * 100
    df_sim['Entry_Signal'] = (df_sim['Confluence_Score'] >= 80).astype(int)

    # State Machine Execution
    position = 0
    positions = []

    # Fast iteration over numpy arrays for speed
    entry_signals = df_sim['Entry_Signal'].values
    z_moms = df_sim['Z_Gold_Mom'].values
    macros = df_sim['Composite_Macro'].values

    for i in range(len(df_sim)):
        if position == 0 and entry_signals[i] == 1:
            position = 1
        elif position == 1 and (z_moms[i] < -0.5 or macros[i] < -0.5):
            position = 0
        positions.append(position)

    df_sim['Position'] = positions
    df_sim['Strategy_Ret'] = df_sim['Position'].shift(1) * df_sim['Gold_Ret']

    # Clean NaNs to calculate exact performance
    df_clean = df_sim.dropna(subset=['ATR_Baseline']).copy()

    if len(df_clean) > 0:
        cum_strat = np.exp(df_clean['Strategy_Ret'].cumsum())
        years = len(df_clean) / 252

        cagr = (cum_strat.iloc[-1] ** (1 / years) - 1) * 100
        max_dd = ((cum_strat - cum_strat.cummax()) / cum_strat.cummax()).min() * 100
        active_days = (df_clean['Position'] == 1).sum()

        optimization_results.append({
            'ATR_Period': atr_period,
            'CAGR_Percent': round(cagr, 2),
            'Max_Drawdown_Percent': round(max_dd, 2),
            'Active_Market_Days': active_days,
            'Final_Capital_Multiplier': round(cum_strat.iloc[-1], 2)
        })

